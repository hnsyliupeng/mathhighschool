#!/usr/bin/env python3
"""Build the optional Chinese UI font subset from the pinned OFL source font.

Runtime still includes the full fontsource unicode subsets as a fallback for
characters not in the static UI. Rebuilding this small subset is optional when
text changes: missing glyphs will continue to use the original fallback.

    python3 -m pip install fonttools brotli
    curl -L -H 'Accept: application/vnd.github.raw+json' \
      https://api.github.com/repos/google/fonts/git/blobs/fb0637bafbcd804fe32152370a1225990745b4bc \
      -o /tmp/NotoSansSC-source.ttf
    python3 scripts/subset-ui-font.py /tmp/NotoSansSC-source.ttf
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE_GIT_BLOB = 'fb0637bafbcd804fe32152370a1225990745b4bc'


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit('usage: python3 scripts/subset-ui-font.py /path/to/NotoSansSC-source.ttf')
    source = Path(sys.argv[1]).read_bytes()
    blob_hash = hashlib.sha1(f'blob {len(source)}\0'.encode() + source).hexdigest()
    if blob_hash != SOURCE_GIT_BLOB:
        raise SystemExit(f'Unexpected upstream font Git blob: {blob_hash}')
    texts = (
        p.read_text(encoding='utf-8') for p in (ROOT / 'src').rglob('*')
        if p.is_file() and p.suffix in {'.ts', '.tsx', '.css', '.json'}
    )
    chars = {
        ord(c) for text in texts for c in text
        if 0x2E80 <= ord(c) <= 0x9FFF or 0xF900 <= ord(c) <= 0xFAFF or 0xFF00 <= ord(c) <= 0xFFEF
    }
    font = TTFont(sys.argv[1], recalcTimestamp=False)
    opts = subset.Options()
    opts.layout_features = ['*']
    opts.flavor = 'woff2'
    job = subset.Subsetter(options=opts)
    job.populate(unicodes=chars)
    job.subset(font)
    font.flavor = 'woff2'
    output = ROOT / 'src/assets/ddg-cjk-subset.woff2'
    output.parent.mkdir(parents=True, exist_ok=True)
    font.save(output)
    ranges = ','.join(f'U+{c:04X}' for c in sorted(chars))
    (ROOT / 'src/ui-font.css').write_text(
        '/* Generated by scripts/subset-ui-font.py; unsupported glyphs use Noto Sans SC fallback. */\n'
        "@font-face{font-family:'DDG CJK';src:url('./assets/ddg-cjk-subset.woff2') format('woff2');"
        "font-style:normal;font-weight:100 900;font-display:swap;unicode-range:"
        + ranges + '}\n', encoding='utf-8'
    )
    print(f'{len(chars)} UI code points -> {output.relative_to(ROOT)} ({output.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
